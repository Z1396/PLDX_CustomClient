// 兵种展示名：三个界面各用一种写法，但「叫什么」只在这里定义一次。
//   slot_name  —— 顶部状态栏在编号后显示（如 "3 步兵"）
//   standalone —— 指挥台卡片 / 登录身份按钮（如 "3号步兵"）
